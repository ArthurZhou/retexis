#!/usr/bin/env python3
"""Emits cross-language fixtures for the Rust test suite.

The simulator is only trustworthy if it speaks the *same* bytes as the Rust
implementation. This script writes a fixture file that
`crates/retexis-core/tests/python_compat.rs` consumes: it rebuilds each
envelope from the FIELD line, encodes it, and asserts the result matches the
HEX line byte for byte. It also checks the HMAC cases.

    python sim/golden.py --write      # regenerate the fixture file
    python sim/golden.py              # print it
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from retexis import wire  # noqa: E402

FIXTURE = os.path.join(
    os.path.dirname(os.path.abspath(__file__)),
    "..",
    "crates",
    "retexis-core",
    "tests",
    "golden_vectors.txt",
)

A = bytes([0xA1] * 16)
B = bytes([0xB2] * 16)
C = bytes([0xC3] * 16)
MSG1 = bytes(range(16))
MSG2 = bytes(reversed(range(16)))
TS = 1_700_000_000_123


def case(label: str, env: wire.Envelope) -> list:
    """Derives every FIELD from the envelope itself.

    Taking the fields from the caller would let a fixture describe something
    different from what it encodes — which is exactly the bug this test is
    meant to catch.
    """
    env.created_ms = TS
    fields = [
        f"kind={wire.KIND_NAMES[env.kind]}",
        f"src={env.src.hex()}",
        f"dst={'-' if env.dst is None else env.dst.hex()}",
        f"id={env.msg_id.hex()}",
        f"ttl={env.ttl}",
        f"hops={env.hops}",
        f"flags={env.flags}",
        f"ts={env.created_ms}",
    ]
    if env.kind == wire.KIND_DATA:
        fields.append(f"channel={env.channel}")
        fields.append(f"ctype={env.ctype}")
        fields.append(f"payload={env.payload.hex()}")
    elif env.kind == wire.KIND_HELLO:
        fields.append(f"name={wire.truncate_name(env.name).decode('utf-8')}")
        fields.append(f"link_id={env.link_id}")
    elif env.kind == wire.KIND_ROUTE:
        joined = "|".join(f"{n.hex()}:{m}:{name}" for n, m, name in env.entries)
        fields.append(f"entries={joined}")
    elif env.kind == wire.KIND_ACK:
        fields.append(f"acked={env.acked.hex()}")
    return [
        f"CASE {label}",
        "FIELD " + " ".join(fields),
        "HEX " + wire.encode(env).hex(),
        "",
    ]


def build_fixture() -> str:
    lines = [
        "# retexis wire-format fixtures, generated by sim/golden.py",
        "# Do not edit by hand: python sim/golden.py --write",
        "#",
        "# Each case is rebuilt by the Rust test from the FIELD line, encoded,",
        "# and compared with the HEX line. Decoding HEX must give back the same",
        "# field values, so this pins both directions of the codec.",
        "#",
        "# Field values are derived from the envelope, never passed in by hand.",
        "",
    ]

    env = wire.data_env(A, None, b"hello mesh", ttl=8, created_ms=TS)
    env.msg_id = MSG1
    lines += case("data-broadcast", env)

    env = wire.data_env(B, C, b"unicast with auth", ttl=5, created_ms=TS)
    env.msg_id = MSG2
    env.flags = wire.FLAG_AUTH | wire.FLAG_ACK_REQ
    env.hops = 2
    lines += case("data-unicast-auth-ackreq", env)

    env = wire.data_env(C, A, b"", ttl=1, created_ms=TS)
    env.msg_id = MSG1
    lines += case("data-empty-payload", env)

    env = wire.data_env(A, B, bytes(range(256)), ttl=8, created_ms=TS, ctype=1)
    env.msg_id = MSG2
    lines += case("data-binary-256", env)

    env = wire.hello_env(A, "alice", link_id=42, created_ms=TS)
    env.msg_id = MSG1
    lines += case("hello", env)

    long_name = "\u8282\u70b9" * 30  # 180 bytes of 3-byte chars, truncated to <= 48
    env = wire.hello_env(B, long_name, link_id=0xDEAD_BEEF, created_ms=TS)
    env.msg_id = MSG2
    lines += case("hello-long-name", env)

    env = wire.route_env(
        A,
        [(A, 0, "alice"), (B, 1, "bob"), (C, 3, "")],
        created_ms=TS,
    )
    env.msg_id = MSG1
    lines += case("route", env)

    env = wire.route_env(B, [], created_ms=TS)
    env.msg_id = MSG2
    lines += case("route-empty", env)

    env = wire.ack_env(C, A, MSG1, ttl=8, created_ms=TS)
    env.msg_id = MSG2
    lines += case("ack", env)

    env = wire.bye_env(A, created_ms=TS)
    env.msg_id = MSG1
    lines += case("bye", env)

    # HMAC vectors: the Rust Sealer must produce the same tags.
    key = wire.key_from_passphrase("retexis golden key")
    lines.append("# HMAC-SHA256, key = sha256(\"retexis golden key\")")
    for label, msg in [
        ("empty", b""),
        ("short", b"Hi There"),
        ("100-bytes", bytes(range(100))),
    ]:
        tag = wire.seal(key, msg)[len(msg):]
        lines.append(f"HMAC label={label} key={key.hex()} msg={msg.hex()} tag={tag.hex()}")
    lines.append("")

    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="emit retexis cross-language fixtures")
    ap.add_argument("--write", action="store_true", help=f"write {FIXTURE}")
    args = ap.parse_args(argv)

    text = build_fixture()
    if args.write:
        path = os.path.normpath(FIXTURE)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {path}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
